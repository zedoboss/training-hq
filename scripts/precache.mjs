// Writes the generated app files: app/sw.js (the service worker, from scripts/sw.template.js, with the version and
// file list inside it), app/precache.js (the same list, for the page) and app/version.json (the version, never
// cached, so the page can see whether a newer one is out). The version is a hash of every app file.
// Run by the Mac server at start, by the GitHub Pages deploy, and by hand before testing locally.
// app/vendor/ (the Squat Depth pose library and models, about 40 MB) is left out of the list and the version: the
// service worker keeps those files in their own store, so an app update never downloads them again.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = fileURLToPath(new URL('../app/', import.meta.url));
const TEMPLATE = fileURLToPath(new URL('./sw.template.js', import.meta.url));
const SKIP = new Set(['precache.js', 'sw.js', 'version.json', '.DS_Store']);

const VENDOR_DIR = 'vendor';

function walk(dir, top = false) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.startsWith('.') || (top && name === VENDOR_DIR)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

export function buildPrecache(appDir = APP_DIR) {
  const files = walk(appDir, true).filter((f) => !f.endsWith('.txt'));
  const hash = createHash('sha256');
  const rel = files.map((f) => relative(appDir, f).split(sep).join('/'));
  for (let i = 0; i < files.length; i++) {
    hash.update(rel[i]);
    hash.update(readFileSync(files[i]));
  }
  hash.update(readFileSync(TEMPLATE));
  const version = hash.digest('hex').slice(0, 12);
  return { version, files: ['./', 'precache.js', ...rel] };
}

export function writePrecache(appDir = APP_DIR) {
  const manifest = buildPrecache(appDir);
  const line = `self.TRAINING_HQ_PRECACHE = ${JSON.stringify(manifest, null, 1)};`;
  writeFileSync(join(appDir, 'precache.js'), `// Generated by scripts/precache.mjs. Do not edit.\n${line}\n`);
  const sw = readFileSync(TEMPLATE, 'utf8');
  if (!sw.includes('/*PRECACHE*/')) throw new Error('sw.template.js lost its /*PRECACHE*/ marker');
  writeFileSync(join(appDir, 'sw.js'), `// Generated by scripts/precache.mjs from scripts/sw.template.js. Do not edit. Version ${manifest.version}.\n${sw.replace('/*PRECACHE*/', line)}`);
  writeFileSync(join(appDir, 'version.json'), `${JSON.stringify({ version: manifest.version })}\n`);
  return manifest;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { version, files } = writePrecache();
  console.log(`precache.js written: version ${version}, ${files.length} entries`);
}
