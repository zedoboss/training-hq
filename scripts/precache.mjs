// Writes app/precache.js: the list of app files the service worker keeps offline,
// plus a version hash that changes whenever any app file changes.
// Run by the Mac server at start and by the GitHub Pages deploy.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = fileURLToPath(new URL('../app/', import.meta.url));
const SKIP = new Set(['precache.js', 'sw.js', '.DS_Store']);

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

export function buildPrecache(appDir = APP_DIR) {
  const files = walk(appDir).filter((f) => !f.endsWith('.txt'));
  const hash = createHash('sha256');
  const rel = files.map((f) => relative(appDir, f).split(sep).join('/'));
  for (let i = 0; i < files.length; i++) {
    hash.update(rel[i]);
    hash.update(readFileSync(files[i]));
  }
  hash.update(readFileSync(join(appDir, 'sw.js')));
  const version = hash.digest('hex').slice(0, 12);
  return { version, files: ['./', 'precache.js', ...rel] };
}

export function writePrecache(appDir = APP_DIR) {
  const manifest = buildPrecache(appDir);
  writeFileSync(
    join(appDir, 'precache.js'),
    `// Generated by scripts/precache.mjs. Do not edit.\nself.TRAINING_HQ_PRECACHE = ${JSON.stringify(manifest, null, 1)};\n`
  );
  return manifest;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { version, files } = writePrecache();
  console.log(`precache.js written: version ${version}, ${files.length} entries`);
}
